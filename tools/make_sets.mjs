// make_sets.mjs — build 4 matched phrase sets + practice from the official MacKenzie & Soukoreff list
// (공식 문구 목록에서 길이·난이도를 맞춘 4세트와 연습 문장 생성)
//
// Usage:  node tools/make_sets.mjs path/to/phrases2.txt > data/phrases.json
//   phrases2.txt comes from https://www.yorku.ca/mack/PhraseSets.zip (not stored in this repo).
//
// Method (tutor feedback 11/9: different sentences per condition, matched in length and difficulty):
//   1. Keep lowercase a–z phrases of 24–33 characters.
//   2. Difficulty d = z(mean word length) + z(letter rarity) + z(key travel).
//   3. For each length, sort by d and take the 4 consecutive phrases with the smallest d spread → a "quad".
//      Pick the 8 lengths whose quads are tightest. Position k of every set comes from quad k,
//      so the k-th phrases of the four sets have the SAME length and nearly the same difficulty.
//   4. Assign the 4 phrases of each quad to sets A–D by a seeded hill-climb that minimises
//      the spread of set means across all features.
//   5. Shuffle the 8 positions (same order for every set), pick 6 practice phrases from the rest.
import { readFileSync } from 'node:fs';
import { phraseFeatures, setStats, FEATURE_NAMES } from '../js/phrasestats.js';

const SEED = 20261109;
const PER_SET = 8, N_SETS = 4, N_PRACTICE = 6, LEN_MIN = 24, LEN_MAX = 33;

function mulberry32(a) {
  return () => { a |= 0; a = a + 0x6D2B79F5 | 0; let t = Math.imul(a ^ a >>> 15, 1 | a); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
}
const rng = mulberry32(SEED);
const shuffle = xs => { const a = [...xs]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
const mean = xs => xs.reduce((s, x) => s + x, 0) / xs.length;
const sd = xs => { const m = mean(xs); return Math.sqrt(mean(xs.map(x => (x - m) ** 2))); };

const file = process.argv[2];
if (!file) { console.error('usage: node tools/make_sets.mjs phrases2.txt'); process.exit(1); }
const all = readFileSync(file, 'latin1').split(/\r?\n/).map(s => s.trim()).filter(Boolean);
const pool = [...new Set(all)].filter(p => /^[a-z ]+$/.test(p) && !/  /.test(p));

const feats = new Map(pool.map(p => [p, phraseFeatures(p)]));
const zParams = Object.fromEntries(['awl', 'rarity', 'travel'].map(k => { const xs = pool.map(p => feats.get(p)[k]); return [k, { m: mean(xs), s: sd(xs) }]; }));
const diff = p => ['awl', 'rarity', 'travel'].reduce((s, k) => s + (feats.get(p)[k] - zParams[k].m) / zParams[k].s, 0);

// Step 3: tightest quad per length
const quads = [];
for (let L = LEN_MIN; L <= LEN_MAX; L++) {
  const ps = pool.filter(p => p.length === L).sort((a, b) => diff(a) - diff(b));
  let best = null;
  for (let i = 0; i + 4 <= ps.length; i++) {
    const q = ps.slice(i, i + 4), spread = diff(q[3]) - diff(q[0]);
    if (!best || spread < best.spread) best = { len: L, q, spread };
  }
  if (best) quads.push(best);
}
const chosen = [...quads].sort((a, b) => a.spread - b.spread).slice(0, PER_SET).sort((a, b) => a.len - b.len);

// Step 4: seeded hill-climb over within-quad assignments
const fScale = Object.fromEntries(FEATURE_NAMES.map(k => [k, sd(pool.map(p => feats.get(p)[k])) || 1]));
const build = perm => Array.from({ length: N_SETS }, (_, s) => chosen.map((c, k) => c.q[perm[k][s]]));
const cost = perm => {
  const stats = build(perm).map(setStats);
  return FEATURE_NAMES.reduce((t, k) => { const v = stats.map(s => s[k]); return t + (Math.max(...v) - Math.min(...v)) / fScale[k]; }, 0);
};
let perm = chosen.map(() => shuffle([0, 1, 2, 3]));
let c0 = cost(perm);
for (let it = 0; it < 20000; it++) {
  const k = Math.floor(rng() * PER_SET), a = Math.floor(rng() * 4), b = Math.floor(rng() * 4);
  if (a === b) continue;
  const next = perm.map(r => [...r]);
  [next[k][a], next[k][b]] = [next[k][b], next[k][a]];
  const c1 = cost(next);
  if (c1 <= c0) { perm = next; c0 = c1; }
}

// Step 5: same shuffled position order for every set; practice from the rest
const order = shuffle([...Array(PER_SET).keys()]);
const sets = build(perm).map(set => order.map(i => set[i]));
const used = new Set(sets.flat());
const practice = shuffle(pool.filter(p => !used.has(p) && p.length >= 22 && p.length <= 28)).slice(0, N_PRACTICE);

const round = o => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, +v.toFixed(3)]));
process.stdout.write(JSON.stringify({
  _note: 'Generated by tools/make_sets.mjs from the official phrases2.txt. Different phrases per condition; the k-th phrase of each set has the same length and nearly the same difficulty (tutor feedback 2026-11-09). Set S[(k+p) mod 4] is assigned per participant.',
  source: 'MacKenzie, I. S., & Soukoreff, R. W. (2003). Phrase sets for evaluating text entry techniques. CHI EA 2003. https://doi.org/10.1145/765891.765971 — phrases2.txt from https://www.yorku.ca/mack/PhraseSets.zip',
  seed: SEED,
  filter: `lowercase a-z, ${LEN_MIN}-${LEN_MAX} chars (practice 22-28)`,
  difficulty: 'mean word length, letter rarity (mean -log2 English letter frequency), key travel (mean distance between consecutive key centers)',
  practice,
  sets,
  stats: sets.map(s => round(setStats(s))),
}, null, 2) + '\n');
